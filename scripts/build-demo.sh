#!/usr/bin/env bash
# Builds the wasm demo into _site/ (not checked in):
#   _site/index.html, minimal.html, script.js, style.css   the pages, copied from web/
#   _site/pkg/                               wasm-pack output
#   _site/default-fonts.js                   base64 default fonts for the HTML examples
#   _site/examples/assets/...                assets the demo fetches at runtime
# Used by .github/workflows/static.yml (Pages deploy), demo-e2e.yml (headless
# tests) and locally: bash scripts/build-demo.sh
set -euo pipefail
cd "$(dirname "$0")/.."

SITE=_site
rm -rf "$SITE"
mkdir -p "$SITE"

wasm-pack build --target web --no-pack --no-typescript --release \
  --out-dir "$SITE/pkg" \
  --no-default-features --features "html,js-sys,gif,jpeg,png,pnm,tiff,bmp,webp"

cp web/index.html web/minimal.html web/script.js web/style.css "$SITE/"

# script.js fetches ./examples/assets/img/cat.jpg for the recipe example.
mkdir -p "$SITE/examples/assets/img"
cp examples/assets/img/cat.jpg "$SITE/examples/assets/img/"

{
  echo "// GENERATED by scripts/build-demo.sh, do not edit, not checked in."
  echo "export const DEFAULT_FONTS = {"
  for f in Helvetica.ttf Helvetica-Bold.ttf Helvetica-Oblique.ttf \
           Helvetica-BoldOblique.ttf Times.ttf Courier.ttf \
           RobotoMedium.ttf NotoSansJP-Regular.otf; do
    p="examples/assets/fonts/$f"
    [ -f "$p" ] || { echo "missing $p" >&2; exit 1; }
    # `base64 | tr` instead of GNU-only `base64 -w0`, so this also runs on macOS.
    printf '  "%s": "%s",\n' "$f" "$(base64 < "$p" | tr -d '\n')"
  done
  echo "};"
} > "$SITE/default-fonts.js"

echo "demo built: $SITE/ (pkg $(du -sh "$SITE/pkg" | cut -f1), default-fonts.js $(du -sh "$SITE/default-fonts.js" | cut -f1))"
